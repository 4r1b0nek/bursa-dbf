-- Skema D1 (SQLite) untuk Bursa DBF API.
-- Terapkan: npx wrangler d1 execute bursa-dbf --remote --file=schema.sql

PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS PENGGUNA (
  ID        INTEGER PRIMARY KEY,
  USERNAME  TEXT NOT NULL COLLATE NOCASE UNIQUE,
  NAMA      TEXT NOT NULL,
  ROLE      TEXT NOT NULL CHECK (ROLE IN ('ADMIN', 'USER')),
  PASSHASH  TEXT NOT NULL,
  SALT      TEXT NOT NULL,
  ITER      INTEGER NOT NULL,
  STATUS    TEXT NOT NULL DEFAULT 'AKTIF',
  EXPIRED   TEXT,
  CREATED   TEXT NOT NULL,
  UPDATED   TEXT NOT NULL,
  MUSTCHG   TEXT NOT NULL DEFAULT 'Y',
  CATATAN   TEXT
);

CREATE TABLE IF NOT EXISTS SAHAM (
  KODE      TEXT PRIMARY KEY,
  NAMA      TEXT NOT NULL,
  SEKTOR    TEXT,
  MODEL     TEXT,
  HARGA     REAL,
  MCAP_T    REAL,
  EPS       REAL,
  BVPS      REAL,
  PE        REAL,
  PB        REAL,
  DY        REAL,
  DPS       REAL,
  PAYOUT    REAL,
  ROE       REAL,
  ROA       REAL,
  PM        REAL,
  OM        REAL,
  DER       REAL,
  CR        REAL,
  ICR       REAL,
  EVEBITDA  REAL,
  FCF       INTEGER,
  DEBT      INTEGER,
  EQUITY    INTEGER,
  CASH      INTEGER,
  PEAVG5    REAL,
  PBAVG5    REAL,
  FV        REAL,
  MOS       REAL,
  SKOR      REAL,
  RATING    TEXT,
  KEPUTUSAN TEXT,
  BINTANG   REAL,
  LEVEL_AKUM TEXT,
  LEVEL_BUY TEXT,
  TARGET    TEXT,
  CUTLOSS   REAL,
  RINGKASAN TEXT,
  UPDAT     TEXT
);

CREATE TABLE IF NOT EXISTS VALUASI (
  KODE    TEXT PRIMARY KEY,
  MODEL   TEXT,
  BOBOT   TEXT,
  DDM     REAL,
  DDM_LO  REAL,
  DDM_HI  REAL,
  PEFAIR  REAL,
  PEVALUE REAL,
  PBF     REAL,
  PBVALUE REAL,
  FV      REAL,
  FV_LO   REAL,
  FV_HI   REAL,
  MOS     REAL,
  BULL1   REAL, BULL3 REAL, BULL5 REAL,
  BASE1   REAL, BASE3 REAL, BASE5 REAL,
  BEAR1   REAL, BEAR3 REAL, BEAR5 REAL
);

CREATE TABLE IF NOT EXISTS TEKNIKAL (
  KODE     TEXT PRIMARY KEY,
  MA20     REAL, MA50 REAL, MA200 REAL,
  RSI14    REAL,
  MACD     REAL, MACDSIG REAL, MACDHIST REAL,
  HI20     REAL, LO20 REAL, HI52 REAL, LO52 REAL,
  ATR      REAL, ATRPCT REAL, VOLRATIO REAL,
  CHG52    REAL,
  DISTMA20 REAL, DISTMA50 REAL, DISTMA200 REAL
);

CREATE TABLE IF NOT EXISTS SKOR (
  KODE  TEXT PRIMARY KEY,
  FUND  INTEGER,
  VAL   INTEGER,
  DIV   INTEGER,
  TECH  INTEGER,
  RISK  INTEGER,
  PROS  INTEGER,
  TOTAL REAL
);

CREATE TABLE IF NOT EXISTS DIVIDEN (
  KODE   TEXT NOT NULL,
  TAHUN  INTEGER NOT NULL,
  DPS    REAL NOT NULL,
  TIPE   TEXT NOT NULL,
  PRIMARY KEY (KODE, TAHUN, TIPE)
);

CREATE TABLE IF NOT EXISTS HISTORIK (
  KODE    TEXT NOT NULL,
  MINGGU  INTEGER NOT NULL,
  PERIODE TEXT,
  HARGA   REAL,
  PRIMARY KEY (KODE, MINGGU)
);

CREATE TABLE IF NOT EXISTS PARAM (
  KUNCI TEXT PRIMARY KEY,
  NILAI TEXT
);

CREATE TABLE IF NOT EXISTS LOG_BULAN (
  BULAN     TEXT PRIMARY KEY,
  TGL       TEXT,
  IHSG      REAL,
  YIELD     REAL,
  MOS       REAL,
  JML_MURAH INTEGER,
  JML_BUY   INTEGER,
  SKOR      REAL,
  CATATAN   TEXT,
  CREATED_AT TEXT,
  CREATED_BY INTEGER
);

CREATE TABLE IF NOT EXISTS TRANSAKSI (
  ID      INTEGER PRIMARY KEY,
  USER_ID INTEGER NOT NULL DEFAULT 1,
  TANGGAL TEXT NOT NULL,
  KODE    TEXT NOT NULL,
  JENIS   TEXT NOT NULL CHECK (JENIS IN ('BELI', 'JUAL')),
  LOT     INTEGER NOT NULL,
  HARGA   REAL NOT NULL,
  FEE     REAL NOT NULL DEFAULT 0,
  CATATAN TEXT
);

CREATE INDEX IF NOT EXISTS IDX_TRANSAKSI_USER ON TRANSAKSI (USER_ID, TANGGAL);
CREATE INDEX IF NOT EXISTS IDX_TRANSAKSI_KODE ON TRANSAKSI (KODE);
CREATE INDEX IF NOT EXISTS IDX_DIVIDEN_KODE ON DIVIDEN (KODE, TAHUN);
CREATE INDEX IF NOT EXISTS IDX_HISTORIK_KODE ON HISTORIK (KODE, MINGGU);
CREATE INDEX IF NOT EXISTS IDX_PENGGUNA_USERNAME ON PENGGUNA (USERNAME);
